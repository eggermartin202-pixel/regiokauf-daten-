private func v(_ pl: String, _ de: String, _ level: Level, _ topic: String,
               fem: String? = nil, note: String? = nil) -> VocabCard {
    VocabCard(id: "v_" + Alt.primary(pl).lowercased(), pl: pl, de: de, level: level,
              topic: topic, plFem: fem, note: note)
}

private func g(_ id: String, _ sentence: String, _ answer: String, _ options: [String],
               _ de: String, _ level: Level, _ tag: String, _ explanation: String,
               fem: String? = nil, femOptions: [String]? = nil) -> GrammarItem {
    GrammarItem(id: "g_" + id, sentence: sentence, answer: answer, options: options, de: de,
                level: level, tag: tag, explanation: explanation,
                answerFem: fem, optionsFem: femOptions)
}

